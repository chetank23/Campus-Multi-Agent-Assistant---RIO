"""
tests/api/test_timetable_privacy_safeguards.py
---------------------------------------------
Comprehensive P0 Privacy Safeguard Tests:
Ensures a timetable generated by any workflow NEVER becomes visible to
faculty, students, coordinators, or query tools before explicit Admin publication.

Verifies:
1. Freshly generated timetable is saved as a private draft and is completely invisible.
2. Validated timetable remains completely invisible.
3. Approved timetable remains completely invisible.
4. Only explicit admin publication (/timetable/versions/{id}/publish) reveals it.
5. Recalling instantly revokes visibility across all portals and query agents.
6. Regenerating creates a new private draft without disturbing an active published timetable.
"""

