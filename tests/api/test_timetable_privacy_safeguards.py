    def test_05_explicit_admin_publish_reveals_schedule_authoritatively(
        self, admin_token, faculty_token, student_token, faculty_user, student_user
    ):
        """
        5. Only explicit publication (/timetable/versions/{id}/publish):
           - Changes status to PUBLISHED and sets published_at.
           - Creates canonical Timetable rows with status='PUBLISHED'.
           - Activates entries with status='ACTIVE' and attaches them to canonical Timetable.
           - Makes schedule visible across faculty, student, department queries, and agent tools.
        """
        vid = TestTimetablePrivacySafeguards.created_version_id
        pub_resp = client.post(
            f"/timetable/versions/{vid}/publish",
            headers={"Authorization": f"Bearer {admin_token}"},
        )
        assert pub_resp.status_code == 200, f"Publish failed: {pub_resp.text}"
        data = pub_resp.json()
        assert data["status"] == "PUBLISHED"

        with Session(engine) as db:
            ver = db.query(TimetableVersion).filter(TimetableVersion.id == vid).first()
            assert ver.status == "PUBLISHED"
            assert ver.published_at is not None

            # Entries must now be ACTIVE and attached to canonical timetables
            entries = db.query(TimetableEntry).filter(TimetableEntry.version_id == vid).all()
            assert len(entries) > 0
            for e in entries:
                assert e.status == "ACTIVE"
                assert e.timetable_id is not None

            # Canonical timetable exists in PUBLISHED status
            canon_count = db.query(Timetable).filter(Timetable.status == "PUBLISHED").count()
            assert canon_count > 0

        # Now non-admin endpoints must see the published schedule
        f_resp = client.get("/faculty/department-timetable", headers={"Authorization": f"Bearer {faculty_token}"})
        assert f_resp.status_code == 200
        assert len(f_resp.json().get("entries", [])) > 0, "Published timetable entries must be visible on department timetable!"

        # Query tools must see the published schedule
        with Session(engine) as db:
            fac_user_obj = db.query(User).filter(User.id == faculty_user["id"]).first()
            assert fac_user_obj is not None
            f_sched = get_faculty_schedule_data(db, fac_user_obj)
            # If the faculty has scheduled entries in this version, tool returns them
            fac_entries = [e for e in entries if e.faculty_id == faculty_user["faculty_id"]]
            if fac_entries:
                assert len(f_sched.get("entries", [])) > 0

        # Room availability: Published entry must now properly occupy the room
        if TestTimetablePrivacySafeguards.target_room_id and TestTimetablePrivacySafeguards.target_slot_id:
            room_resp = client.get(
                f"/rooms/{TestTimetablePrivacySafeguards.target_room_id}/availability",
                params={"check_date": "2026-11-26", "slot_id": TestTimetablePrivacySafeguards.target_slot_id},
                headers={"Authorization": f"Bearer {faculty_token}"},
            )
            assert room_resp.status_code == 200
            assert room_resp.json()["available"] is False, "Published class must occupy room in availability check!"

    def test_06_recalling_instantly_revokes_visibility(
        self, admin_token, faculty_token, student_token, faculty_user, student_user
    ):
        """
        6. Recalling a published timetable immediately revokes public access:
           - Version status becomes RECALLED.
           - Canonical entries are deactivated/unlinked.
           - Faculty and student queries immediately return 0 active entries.
        """
        vid = TestTimetablePrivacySafeguards.created_version_id
        recall_resp = client.post(
            f"/timetable/versions/{vid}/recall",
            headers={"Authorization": f"Bearer {admin_token}"},
            json={"reason": "Emergency curriculum revision"},
        )
        assert recall_resp.status_code == 200, f"Recall failed: {recall_resp.text}"

        with Session(engine) as db:
            ver = db.query(TimetableVersion).filter(TimetableVersion.id == vid).first()
            assert ver.status == "RECALLED"
            assert ver.recall_reason == "Emergency curriculum revision"

        # Visibility is immediately revoked
        f_resp = client.get("/faculty/department-timetable", headers={"Authorization": f"Bearer {faculty_token}"})
        assert f_resp.status_code == 200
        assert len(f_resp.json().get("entries", [])) == 0, "Recalled timetable entries must NOT be visible!"

        s_resp = client.get("/student/my-timetable", headers={"Authorization": f"Bearer {student_token}"})
        assert s_resp.status_code == 200
        assert len(s_resp.json().get("entries", [])) == 0, "Recalled timetable entries must NOT be visible to student!"

        # Room availability is freed
        if TestTimetablePrivacySafeguards.target_room_id and TestTimetablePrivacySafeguards.target_slot_id:
            room_resp = client.get(
                f"/rooms/{TestTimetablePrivacySafeguards.target_room_id}/availability",
                params={"check_date": "2026-11-26", "slot_id": TestTimetablePrivacySafeguards.target_slot_id},
                headers={"Authorization": f"Bearer {faculty_token}"},
            )
            assert room_resp.status_code == 200
            assert room_resp.json()["available"] is True, "Recalled timetable must release room availability!"

    def test_07_regenerating_creates_new_private_draft_without_disturbing_existing_published(
        self, admin_token, faculty_token, test_academic_scope
    ):
        """
        7. Regenerating when a timetable is published:
           - First re-publishes v1.
           - Generates v2 with force_regenerate=True.
           - v2 is GENERATED, private draft (UNPUBLISHED).
           - v1 remains PUBLISHED and visible to users.
           - After v2 is validated, approved, and published:
             - v1 is archived.
             - v2 becomes PUBLISHED.
        """
        vid = TestTimetablePrivacySafeguards.created_version_id
        # Re-validate, approve, and re-publish v1
        client.post(f"/timetable/versions/{vid}/validate", headers={"Authorization": f"Bearer {admin_token}"})
        client.post(f"/timetable/versions/{vid}/approve", headers={"Authorization": f"Bearer {admin_token}"})
        repub_resp = client.post(f"/timetable/versions/{vid}/publish", headers={"Authorization": f"Bearer {admin_token}"})
        assert repub_resp.status_code == 200

        # Confirm v1 is active and visible
        f_before = client.get("/faculty/department-timetable", headers={"Authorization": f"Bearer {faculty_token}"})
        assert len(f_before.json().get("entries", [])) > 0, "Published v1 must be visible"

        # Generate v2 (force_regenerate=True)
        gen2 = client.post(
            "/timetable/generate",
            headers={"Authorization": f"Bearer {admin_token}"},
            json={
                "academic_year_id": test_academic_scope["academic_year_id"],
                "semester_id": test_academic_scope["semester_id"],
                "department_id": test_academic_scope["department_id"],
                "program_id": test_academic_scope["program_id"],
                "force_regenerate": True,
            },
        )
        assert gen2.status_code == 200
        v2_id = gen2.json()["version_id"]
        assert v2_id != vid

        with Session(engine) as db:
            v1_db = db.query(TimetableVersion).filter(TimetableVersion.id == vid).first()
            v2_db = db.query(TimetableVersion).filter(TimetableVersion.id == v2_id).first()

            # v2 must be GENERATED draft
            assert v2_db.status == "GENERATED"
            assert v2_db.published_at is None

            # v1 must remain PUBLISHED while v2 is in draft
            assert v1_db.status == "PUBLISHED"

        # Faculty department timetable must STILL see v1, NOT v2
        f_mid = client.get("/faculty/department-timetable", headers={"Authorization": f"Bearer {faculty_token}"})
        mid_entries = f_mid.json().get("entries", [])
        assert len(mid_entries) > 0
        for e in mid_entries:
            assert e["version_id"] == vid, "Mid-generation must still display v1 entries"

        # Now validate, approve, and publish v2
        client.post(f"/timetable/versions/{v2_id}/validate", headers={"Authorization": f"Bearer {admin_token}"})
        client.post(f"/timetable/versions/{v2_id}/approve", headers={"Authorization": f"Bearer {admin_token}"})
        pub2 = client.post(f"/timetable/versions/{v2_id}/publish", headers={"Authorization": f"Bearer {admin_token}"})
        assert pub2.status_code == 200

        with Session(engine) as db:
            v1_after = db.query(TimetableVersion).filter(TimetableVersion.id == vid).first()
            v2_after = db.query(TimetableVersion).filter(TimetableVersion.id == v2_id).first()

            # v1 must now be ARCHIVED
            assert v1_after.status == "ARCHIVED"
            # v2 must now be PUBLISHED
            assert v2_after.status == "PUBLISHED"

        # Faculty department timetable now shows v2 entries
        f_after = client.get("/faculty/department-timetable", headers={"Authorization": f"Bearer {faculty_token}"})
        after_entries = f_after.json().get("entries", [])
        assert len(after_entries) > 0
        for e in after_entries:
            assert e["version_id"] == v2_id, "After v2 publication, department timetable must show v2 entries"
