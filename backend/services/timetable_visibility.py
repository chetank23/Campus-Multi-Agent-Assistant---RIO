"""
backend/services/timetable_visibility.py
----------------------------------------
Authoritative, centralized predicate and query utilities for Timetable visibility.

BUSINESS RULE:
A timetable generated by any workflow must NEVER become visible to faculty,
students, or coordinators automatically.
Only an explicit administrator publication action (after verification of current
validation and approval) transitions entries to ACTIVE and visible status.

A timetable entry is visible to public stakeholders (students, faculty, coordinators)
if and only if:
1. TimetableEntry.status == 'ACTIVE' (DRAFT, CANCELLED, or RESCHEDULED entries never leak).
2. The entry belongs to an active PUBLISHED container:
   - Either attached to canonical Timetable with status == 'PUBLISHED'
     (and if attached to a TimetableVersion, version status must also be 'PUBLISHED').
   - Or attached to a TimetableVersion with status == 'PUBLISHED' (legacy unlinked canonicals).
"""

from typing import Any
from sqlalchemy import and_, or_
from backend.models.timetable import Timetable, TimetableVersion, TimetableEntry


def published_timetable_entry_predicate(
    entry_cls: Any = TimetableEntry,
    timetable_cls: Any = Timetable,
    version_cls: Any = TimetableVersion,
):
    """
    Centralized, authoritative predicate enforcing that a TimetableEntry is PUBLISHED and visible.
    Requires outer-joining both Timetable and TimetableVersion.
    """
    return and_(
        entry_cls.status == "ACTIVE",
        or_(
            and_(
                timetable_cls.id.isnot(None),
                timetable_cls.status == "PUBLISHED",
                or_(version_cls.id.is_(None), version_cls.status == "PUBLISHED"),
            ),
            and_(
                entry_cls.timetable_id.is_(None),
                version_cls.id.isnot(None),
                version_cls.status == "PUBLISHED",
            ),
        ),
    )


def published_version_entry_predicate(
    entry_cls: Any = TimetableEntry,
    version_cls: Any = TimetableVersion,
):
    """
    Predicate when querying entries directly joined with TimetableVersion.
    """
    return and_(
        entry_cls.status == "ACTIVE",
        version_cls.status == "PUBLISHED",
    )


def published_canonical_entry_predicate(
    entry_cls: Any = TimetableEntry,
    timetable_cls: Any = Timetable,
):
    """
    Predicate when querying entries directly joined with canonical Timetable.
    """
    return and_(
        entry_cls.status == "ACTIVE",
        timetable_cls.status == "PUBLISHED",
    )
